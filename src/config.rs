/// Номинал монеты на каждой из шести линий, в евроцентах.
///
/// Соответствие задаётся программированием самого приёмника — здесь оно просто
/// повторено. Раскладка снята с шильдика экземпляра `06V01/5-14000084-008`
/// (11/06); столбцы там: монета, два канала, выходная линия, число импульсов.
///
/// | Линия | Монета | Каналы | Считаем |
/// |---|---|---|---|
/// | 1 | LVL 1,- | 01, 06 | нет — лат выведен из обращения в 2014 |
/// | 2 | RUR 5,- | 02, 07 | нет |
/// | 3 | UAH 0,50 | 03, 08 | нет |
/// | 4 | UAH 1,- | 04, 09 | нет |
/// | 5 | **EUR 1,-** | 05, 10 | 100 |
/// | 6 | жетоны | 12…16 | 100 |
///
/// Ноль означает «монету не засчитываем», но приёмник её при этом всё равно
/// **проглотит**. Поэтому такие линии обязаны быть заблокированы — см.
/// [`COIN_BLOCK_DEFAULT`] и проверку под ним.
///
/// Жетоны различить нельзя: все пять их каналов сидят на одной линии 6.
/// Значение 100 — предположение «жетон равен одному евро»; поставьте своё.
pub const COIN_VALUES: [u32; 6] = [0, 0, 0, 0, 100, 100];

/// Какие линии заблокированы сразу после старта. Бит 0 — линия 1.
///
/// Блокируем всё, что не считаем. Иначе старый лат физически провалится в
/// кассу, не дав кредита: для клиента это потеря денег, и заметить её он
/// сможет только по отсутствию товара.
///
/// Меняется на ходу через [`MQTT_TOPIC_COIN_BLOCK`].
pub const COIN_BLOCK_DEFAULT: u8 = 0b0000_1111;

/// Номинал и блокировка обязаны быть согласованы: линия либо приносит деньги,
/// либо закрыта. Третьего — «монету берём, кредит не даём» — быть не должно,
/// и проверяется это на этапе компиляции, а не на живых клиентах.
const _: () = {
    let mut line = 0;
    while line < COIN_VALUES.len() {
        let paid = COIN_VALUES[line] != 0;
        let blocked = COIN_BLOCK_DEFAULT & (1 << line) != 0;
        assert!(
            paid != blocked,
            "линия должна быть либо с номиналом, либо заблокирована по умолчанию"
        );
        line += 1;
    }
};

