/// Монеты и коды, которыми приёмник о них сообщает.
///
/// Код — состояние всех шести линий, снятое разом. Однобитный код означает
/// «одна монета на линию», многобитный — двоичное кодирование, которое
/// документация допускает прямо («possible to transmit coin signals in a binary
/// code or assign more than one line to a type of coin»).
///
/// # Почему монет вдвое больше, чем на самом деле
///
/// Столбец на шильдике со значениями 1…6 читается двояко, и однозначно его
/// решает только монета:
///
/// * **номер линии** — тогда 1 евро это линия 5, то есть `0b010000`;
/// * **двоичный код** — тогда 1 евро это пины 1+3, то есть `0b000101`.
///
/// Рабочий автомат на MSP430 (`bahilizator_kwt_svn`) устроен по первому
/// варианту: там шесть каналов, по монете на каждый, а номиналы оператор
/// вводит с экрана. Но это другой экземпляр приёмника, и настроен он мог быть
/// иначе.
///
/// Поэтому здесь перечислены **оба** кода. Столкнуться они не могут: при
/// однобитной раскладке `0b000101` не появится никогда (две линии разом не
/// зажигаются), при двоичной — не появится `0b010000` (кода 16 на шильдике
/// нет). Так что ошибиться нельзя, а лог сразу скажет, какой вариант ваш:
///
/// ```text
/// COIN: EUR 1 (линия 5) (код 0b010000), номинал 100, кредит 100
/// ```
///
/// Увидели — лишнюю строку отсюда удалите.
///
/// # Если код окажется третьим
///
/// Неизвестный код печатается готовым к вписыванию:
///
/// ```text
/// COIN: неизвестный код 0b000101 — впишите его в config::COINS
/// ```
///
/// # Что не считаем
///
/// Лат, рубль и гривна в таблице отсутствуют намеренно: лат выведен из
/// обращения в 2014-м, остальное — чужая валюта. Их коды прошивка напечатает
/// и кредита не даст. Физически глушить их надо переключателями на корпусе —
/// см. [`COIN_BLOCK_DEFAULT`].
///
/// Жетоны различить нельзя: все пять их каналов дают один код. Значение 100 —
/// предположение «жетон равен одному евро»; поставьте своё.
pub const COINS: &[coin::Coin] = &[
    coin::Coin {
        mask: 0b010000,
        value: 100,
        name: "EUR 1 (линия 5)",
    },
    coin::Coin {
        mask: 0b000101,
        value: 100,
        name: "EUR 1 (код 5)",
    },
    coin::Coin {
        mask: 0b100000,
        value: 100,
        name: "жетон (линия 6)",
    },
    coin::Coin {
        mask: 0b000110,
        value: 100,
        name: "жетон (код 6)",
    },
];

/// Какие линии заблокированы сразу после старта. Бит 0 — линия 1.
///
/// Ноль, и это осознанно. При двоичном кодировании закрыть **монету** линиями
/// невозможно: пин 1 участвует и в лате (`1`), и в гривне (`3`), и в евро
/// (`5`), так что блокировка линии калечит чужие коды, а не отсекает лишнее.
///
/// Ненужные монеты глушатся не отсюда, а переключателями на корпусе приёмника:
/// там это делается по каналам, поштучно и надёжно. `S1.1…8` — каналы 1–8,
/// `S2.1…8` — каналы 9–16. Лат, например, занимает каналы 01 и 06, значит
/// выключить надо оба.
///
/// Команда [`MQTT_TOPIC_COIN_BLOCK`] остаётся: она управляет линиями как есть,
/// и на приёмнике с одной монетой на линию работает ожидаемо.
pub const COIN_BLOCK_DEFAULT: u8 = 0;

