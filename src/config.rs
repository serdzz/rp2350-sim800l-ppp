/// Инвертирует ли буферный каскад сигнал полной блокировки на `GP9`.
///
/// Вход `total blocking` приёмника (контакт 6) требует **≥ 3.5 В** для
/// блокировки, а RP2350 выдаёт 3.3 В — впритык под порогом. Поэтому между
/// ними ставится ключ на NPN с подтяжкой линии к +12 В, а он инвертирует:
/// `GP9` низкий → транзистор закрыт → на линии 12 В → блокировка.
///
/// Побочная выгода, ради которой инвертирующий вариант и выбран: пока
/// контроллер в сбросе и вывод не управляется, транзистор закрыт, то есть
/// приёмник **заблокирован**. Монета, брошенная в мёртвый автомат, не будет
/// проглочена без кредита.
///
/// `false` — если вы подключили `GP9` к контакту 6 напрямую. Работать может,
/// но 3.3 В ниже заявленного порога, и за пределами спецификации.
pub const COIN_TOTAL_BLOCK_INVERTED: bool = true;

