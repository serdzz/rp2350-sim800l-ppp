//! Сторожевой таймер: перезагрузка платы, если прошивка встала.
//!
//! # Зачем, если есть свои механизмы восстановления
//!
//! Затем, что они восстанавливают от известных отказов. Автомат стоит без
//! присмотра, и за одно утро мы поймали два разных зависания, которые ни один
//! из них не покрывал: холостой цикл на ошибке UART (исполнитель голодает) и
//! запертую очередь URC (исполнитель жив, обмен с модемом стоит). Сторожевой
//! таймер не разбирается в причине — он просто не даёт висеть часами.
//!
//! # Две проверки, а не одна
//!
//! Кормление из отдельной задачи доказывает лишь то, что исполнитель крутится.
//! Взаимоблокировку в очереди URC такая проверка не заметила бы: там задачи
//! живы, экран перерисовывается, а модем недоступен. Поэтому кормим не
//! безусловно:
//!
//! | Что сломалось | Что замечает |
//! |---|---|
//! | паника, холостой цикл, зависший исполнитель | задача не выполняется, кормить некому |
//! | обмен с модемом встал при живых задачах | [`MODEM_SILENCE_LIMIT`] |
//!
//! # Про порог молчания
//!
//! Он щедрый намеренно. В рабочем режиме модем отвечает не реже чем раз в 30 с
//! (опрос CSQ), но `AT+COPS=?` сканирует сети **молча** и занимает минуты.
//! Перезагрузиться посреди сканирования было бы хуже болезни: устройство
//! никогда бы не дошло до конца поиска сети.

use core::sync::atomic::{AtomicU32, Ordering};

use embassy_rp::watchdog::Watchdog;
use embassy_time::{Duration, Instant, Timer};

/// Аппаратный предел RP2350 — 16.7 с; берём вдвое меньше.
///
/// Запас нужен на редкие длинные операции без точек ожидания. Меньше 4 с
/// ставить не стоит: перерисовка экрана по I2C и подъём мультиплексора иногда
/// занимают заметное время.
const HW_TIMEOUT: Duration = Duration::from_secs(8);

/// Как часто кормить. Вчетверо чаще срабатывания — одно пропущенное кормление
/// не должно приводить к перезагрузке.
const FEED_INTERVAL: Duration = Duration::from_secs(2);

/// Сколько модем может молчать, прежде чем считать связь с ним потерянной.
///
/// Десять минут: `AT+COPS=?` молчит до нескольких минут, и порог обязан быть
/// заведомо больше. Полное молчание дольше этого — не медленная сеть, а
/// заклинивший обмен.
const MODEM_SILENCE_LIMIT: Duration = Duration::from_secs(600);

/// Момент последнего байта от модема, в секундах от старта.
///
/// Секунды, а не миллисекунды: `AtomicU64` на Cortex-M33 нет, а 32 бита
/// миллисекунд кончились бы через 49 суток непрерывной работы — ровно тот
/// срок, ради которого всё это и делается.
static LAST_MODEM_BYTE: AtomicU32 = AtomicU32::new(0);

/// Отметить, что от модема что-то пришло.
///
/// Зовётся из обоих читателей UART — [`crate::cmux_transport::pump`] и обёртки
/// [`crate::io_compat::Compat`], через которую читает `atat`.
pub fn modem_alive() {
    LAST_MODEM_BYTE.store(seconds_now(), Ordering::Relaxed);
}

fn seconds_now() -> u32 {
    Instant::now().as_secs() as u32
}

/// Кормит сторожевой таймер, пока прошивка выглядит живой.
#[embassy_executor::task]
pub async fn watchdog_task(mut watchdog: Watchdog) -> ! {
    // Под отладчиком остановка на точке останова — не зависание.
    watchdog.pause_on_debug(true);
    watchdog.start(HW_TIMEOUT);
    info!(
        "WDT: сторожевой таймер включён, порог {} с",
        HW_TIMEOUT.as_secs()
    );

    let limit = MODEM_SILENCE_LIMIT.as_secs() as u32;

    loop {
        let silence = seconds_now().saturating_sub(LAST_MODEM_BYTE.load(Ordering::Relaxed));

        if silence < limit {
            watchdog.feed(HW_TIMEOUT);
        } else {
            // Не кормим — через HW_TIMEOUT чип перезагрузится сам. Пишем в лог
            // на каждом проходе: строка может не успеть уйти по USB.
            error!(
                "WDT: модем молчит {} с, перезагружаюсь через {} с",
                silence,
                HW_TIMEOUT.as_secs()
            );
        }

        Timer::after(FEED_INTERVAL).await;
    }
}
