//! Монетоприёмник NRI G-13: чтение кода монеты и блокировка.
//!
//! # Подключение
//!
//! | Контакт | Сигнал | Куда |
//! |---|---|---|
//! | 1 | GND | общая земля с платой |
//! | 2 | UB +12 В | отдельный источник 10–16 В, 20 мА |
//! | 7 | output line 1 | GP3 |
//! | 8 | output line 2 | GP4 |
//! | 9 | output line 3 | GP5 |
//! | 10 | output line 4 | GP6 |
//! | 3 | output line 5 | GP7 |
//! | 4 | output line 6 | GP8 |
//! | 6 | total blocking | GP9 через ключ, см. ниже |
//!
//! Нумерация линий и контактов **не совпадает** — на этом легко ошибиться.
//!
//! # Согласование уровней
//!
//! Линии приёмника живут в 12-вольтовом мире, плата — в 3.3-вольтовом, и по
//! каждой линии нужно и читать, и писать. Между ними ставится
//! **двунаправленный преобразователь на BSS138**, по одному на линию: затвор к
//! `+3.3 В`, исток к выводу платы, сток к приёмнику.
//!
//! Внешние резисторы не нужны: со стороны платы работает встроенная подтяжка
//! (её включает [`apply_mask`]), со стороны приёмника — его собственная. Так
//! собран рабочий автомат на MSP430, `main_baord/coin.sch`, `Q10…Q15`.
//!
//! Заводить линии на выводы напрямую нельзя: приём канала задан как `≥ 3.5 В`,
//! а плата выдаёт 3.3 В — под порогом.
//!
//! # Полная блокировка
//!
//! Контакт 6 закрывает приём целиком, независимо от поканальной маски. Активен
//! **высоким**: блокировка `≥ 3.5 В`, приём `≤ 1 В`, выдержит до 35 В.
//!
//! Схема та же, что у линий, плюс подтяжка стока к `+5 В` — в рабочем автомате
//! это `Q5` и `R45` 10 кОм. Каскад **не инвертирует**: `GP9` высокий → полевик
//! закрыт → линия подтянута к 5 В → блокировка.
//!
//! Плюс резистор 10 кОм от `GP9` к `+3.3 В`: без него вывод в сбросе не
//! управляется, линия уходит к нулю, и мёртвый автомат принимает монеты, не
//! давая кредита. С подтяжкой неуправляемое состояние совпадает с безопасным.
//!
//! Полярность задаётся [`config::COIN_TOTAL_BLOCK_INVERTED`].
//!
//! # Монета опознаётся кодом, а не линией
//!
//! Опознанная монета даёт импульс **100 мс** — но не обязательно на одной
//! линии. Приёмник умеет передавать номер монеты **двоичным кодом сразу по
//! нескольким линиям**, и на нашем экземпляре так и сделано: шесть типов монет
//! уложены в три пина, где, например, `0b000101` — это одно евро.
//!
//! Отсюда устройство задачи: снимаем состояние всех шести линий разом,
//! выдерживаем [`SETTLE`] на разбег фронтов, снимаем ещё раз — и ищем
//! получившийся код в [`config::COINS`]. Считать линии по отдельности нельзя:
//! одно евро зажигает два пина, и шесть независимых счётчиков насчитали бы две
//! монеты вместо одной.
//!
//! Затем дожидаемся, пока все линии отпустят, — иначе один импульс был бы
//! посчитан многократно.

use embassy_rp::Peri;
use embassy_rp::gpio::{Flex, Level, Output, Pull};
use embassy_rp::peripherals::PIN_9;
use embassy_sync::blocking_mutex::raw::CriticalSectionRawMutex;
use embassy_sync::watch::Watch;
use embassy_time::{Duration, Instant, Timer};

use crate::coin;
use crate::config;
use crate::mqtt;

/// Текущая маска заблокированных линий.
///
/// [`Watch`], а не атомик: задача линии висит на ожидании импульса, и её нужно
/// уметь разбудить при смене маски. По приёмнику на линию — отсюда параметр
/// [`coin::LINES`].
static BLOCK_MASK: Watch<CriticalSectionRawMutex, u8, { coin::LINES }> = Watch::new();

/// Выставить исходную маску блокировки. Зовётся до запуска задач линий.
///
/// Не полагаемся на «по умолчанию ничего не заблокировано»: линии без номинала
/// обязаны быть закрыты с первой секунды, иначе монета провалится в кассу, не
/// дав кредита. См. [`config::COIN_BLOCK_DEFAULT`].
pub fn init() {
    set_block_mask(config::COIN_BLOCK_DEFAULT);
}

/// Задать, какие линии заблокированы. Задачи подхватят изменение немедленно.
pub fn set_block_mask(mask: u8) {
    BLOCK_MASK.sender().send(mask);
    info!("COIN: маска блокировки 0b{:06b}", mask);
}

/// Полностью ли заблокирован приём. Отдельно от [`BLOCK_MASK`], потому что
/// это независимое состояние: закрытый автомат не отменяет того, какие монеты
/// в нём не принимаются, когда он открыт.
static TOTAL_BLOCK: Watch<CriticalSectionRawMutex, bool, 1> = Watch::new();

/// Закрыть или открыть приём целиком.
pub fn set_total_block(blocked: bool) {
    TOTAL_BLOCK.sender().send(blocked);
    info!(
        "COIN: приём {}",
        if blocked { "заблокирован" } else { "открыт" }
    );
}

/// Заблокирован ли приём целиком. Читает экран.
pub fn total_blocked() -> bool {
    TOTAL_BLOCK.try_get().unwrap_or(false)
}

/// Обработать команду полной блокировки, пришедшую по MQTT.
pub fn apply_total_command(payload: &[u8]) {
    let Ok(text) = core::str::from_utf8(payload) else {
        warn!("COIN: команда полной блокировки не в UTF-8");
        return;
    };

    match coin::parse_total_block(text) {
        Some(blocked) => set_total_block(blocked),
        None => warn!("COIN: непонятная команда, ожидается block или accept"),
    }
}

/// Уровень на `GP9`, соответствующий заданному состоянию.
///
/// Полярность задаётся [`config::COIN_TOTAL_BLOCK_INVERTED`] — см. там про
/// буферный каскад и порог 3.5 В.
const fn total_level(blocked: bool) -> Level {
    if blocked != config::COIN_TOTAL_BLOCK_INVERTED {
        Level::High
    } else {
        Level::Low
    }
}

/// Держит линию полной блокировки (контакт 6 приёмника).
///
/// Вывод создаётся здесь, а не в `main`, чтобы полярность знал ровно один
/// файл. Стартовый уровень — «заблокировано»: до первой команды автомат
/// закрыт, а не принимает монеты неизвестно на каком основании.
#[embassy_executor::task]
pub async fn total_block_task(pin: Peri<'static, PIN_9>) -> ! {
    let mut pin = Output::new(pin, total_level(true));
    let mut rx = unwrap!(TOTAL_BLOCK.receiver());

    // Первое состояние задаём сами: без него приёмник остался бы закрытым до
    // прихода команды, а работать он должен и без связи.
    set_total_block(false);

    loop {
        let blocked = rx.changed().await;
        pin.set_level(total_level(blocked));
    }
}

/// Обработать команду блокировки, пришедшую по MQTT.
pub fn apply_block_command(payload: &[u8]) {
    let Ok(text) = core::str::from_utf8(payload) else {
        warn!("COIN: команда блокировки не в UTF-8");
        return;
    };

    match coin::parse_block_mask(text) {
        Some(mask) => set_block_mask(mask),
        None => warn!("COIN: непонятная команда блокировки, ожидается none, all или «1,3»"),
    }
}

/// Засчитать монету и отправить событие в MQTT.
fn register(coin_found: &coin::Coin) {
    let total = coin::add(coin_found.value);
    info!(
        "COIN: {} (код 0b{:06b}), номинал {}, кредит {}",
        coin_found.name, coin_found.mask, coin_found.value, total
    );

    let mut payload = mqtt::CoinText::new();
    let _ = core::fmt::Write::write_fmt(
        &mut payload,
        format_args!(
            "{{\"coin\":\"{}\",\"code\":{},\"value\":{},\"credit\":{}}}",
            coin_found.name, coin_found.mask, coin_found.value, total
        ),
    );

    // Не блокируемся: очередь переполняется только когда стоит связь, а
    // задерживать из-за этого приём монет нельзя.
    if mqtt::COIN_QUEUE.try_send(payload).is_err() {
        warn!("COIN: очередь публикаций переполнена, событие потеряно");
    }
}

/// Как часто опрашивать линии в покое.
///
/// Импульс длится 100 мс, так что 5 мс дают двадцатикратный запас и стоят
/// сущие копейки процессорного времени.
const POLL: Duration = Duration::from_millis(5);

/// Сколько ждать от первого спада до снятия кода.
///
/// Биты кода зажигаются не идеально одновременно, и снять код сразу — значит
/// прочитать половину: евро (`0b101`) легко превратится в лат (`0b001`).
///
/// 60 мс — не расчёт, а число из рабочего автомата на MSP430
/// (`COIN_ACCEPTOR_PULSE_MIDLE`), отработавшее в поле. Заведомо больше разбега
/// фронтов и заведомо меньше импульса в 100 мс.
const SETTLE: Duration = Duration::from_millis(60);

/// Сколько импульс имеет право длиться, прежде чем считать линию залипшей.
///
/// Оттуда же (`COIN_ACCEPTOR_PULSE_MAX`). Без этого предела цикл ожидания
/// отпускания линий висел бы вечно: оборванный провод или заклинивший выход
/// молча прекратили бы приём монет навсегда, и в логе не было бы ни строчки.
const PULSE_MAX: Duration = Duration::from_millis(250);

/// Снять код со всех линий разом.
///
/// Заблокированные исключаем: мы сами удерживаем их в нуле, и без этого наша
/// же блокировка читалась бы как нажатая линия.
fn sample(pins: &[Flex<'static>; coin::LINES], blocked: u8) -> u8 {
    let mut code = 0u8;
    for (index, pin) in pins.iter().enumerate() {
        if pin.is_low() && !coin::is_blocked(blocked, index) {
            code |= 1 << index;
        }
    }
    code
}

/// Привести линии в состояние, заданное маской блокировки.
fn apply_mask(pins: &mut [Flex<'static>; coin::LINES], blocked: u8) {
    for (index, pin) in pins.iter_mut().enumerate() {
        if coin::is_blocked(blocked, index) {
            // Удерживаем в нуле — для приёмника это и есть блокировка канала.
            // Высокий уровень не выдаём никогда: с той стороны открытый
            // коллектор, и в момент импульса он потянет линию к земле против
            // нашего выхода.
            pin.set_low();
            pin.set_as_output();
        } else {
            pin.set_as_input();
            pin.set_pull(Pull::Up);
        }
    }
}

/// Следит за монетоприёмником: снимает код с линий и засчитывает монету.
///
/// # Почему одна задача, а не шесть
///
/// Потому что монета опознаётся **кодом на нескольких линиях сразу**, а не
/// линией. Шесть независимых задач засчитали бы одно евро (`0b101`) дважды —
/// по разу на каждый зажёгшийся пин.
///
/// # Почему опрос, а не ожидание фронта
///
/// Ждать фронта пришлось бы на шести выводах одновременно, а потом всё равно
/// выдерживать паузу на разбег битов кода. При импульсе в 100 мс опрос раз в
/// [`POLL`] проще, надёжнее и ничего не стоит.
#[embassy_executor::task]
pub async fn coin_task(mut pins: [Flex<'static>; coin::LINES]) -> ! {
    let mut mask_rx = unwrap!(BLOCK_MASK.receiver());
    let mut blocked = mask_rx.try_get().unwrap_or(0);
    apply_mask(&mut pins, blocked);

    loop {
        if let Some(updated) = mask_rx.try_changed() {
            blocked = updated;
            apply_mask(&mut pins, blocked);
        }

        if sample(&pins, blocked) == 0 {
            Timer::after(POLL).await;
            continue;
        }

        // Импульс начался — даём коду установиться и снимаем его целиком.
        Timer::after(SETTLE).await;
        let code = sample(&pins, blocked);

        match coin::lookup(config::COINS, code) {
            Some(found) => register(found),
            None if code == 0 => debug!("COIN: импульс пропал, помеха"),
            None => warn!(
                "COIN: неизвестный код 0b{:06b} — впишите его в config::COINS",
                code
            ),
        }

        // Пока линии не отпущены, новой монеты быть не может.
        //
        // Из этого ожидания намеренно нет выхода по таймауту: пока линия
        // залипла, отличить новую монету от той же самой невозможно, и выход
        // означал бы начисление кредита за каждый проход цикла. Лучше стоять
        // и кричать в лог, чем печатать деньги. Отпустят — продолжим сами.
        let started = Instant::now();
        let mut reported = false;
        while sample(&pins, blocked) != 0 {
            if !reported && started.elapsed() > PULSE_MAX {
                error!(
                    "COIN: линии не отпущены за {} мс (код 0b{:06b}) — обрыв или заклинивший выход, приём монет стоит",
                    PULSE_MAX.as_millis(),
                    sample(&pins, blocked)
                );
                reported = true;
            }
            Timer::after(POLL).await;
        }
        if reported {
            info!("COIN: линии отпущены, приём монет восстановлен");
        }
    }
}
